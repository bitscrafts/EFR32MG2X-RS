//! IEEE 802.15.4 on the EFR32MG24: the two entry points that bring the radio up in that mode.
//!
//! ## Why this is small, and why it is here and not in a crate of its own
//!
//! RAIL is one radio with several protocols under it. The vendor ships them as modules of the same
//! library, and this crate is the Rust face of that library:
//!
//! ```text
//! vendor/rail/protocol/   ble/  ieee802154/  sidewalk/  wmbus/  zwave/
//! src/                    lib.rs (bindings)  ble_config.rs  ieee802154.rs  <- this file
//! ```
//!
//! The blob that `build.rs` already links exports both functions, measured with `nm`:
//! `RAIL_IEEE802154_Init` and `RAIL_IEEE802154_Config2p4GHzRadio`. There is nothing to vendor and no
//! second licence to answer; the 802.15.4 code was always in the archive this crate already links.
//!
//! ## Order matters, and the compiler will not tell you
//!
//! `RAIL_Init` must have run and returned a handle, and the radio must be configured for 802.15.4
//! before `RAIL_IEEE802154_Init` is called. Calling these on a handle configured for BLE does not
//! fail loudly -- it produces a radio that does something, not what you asked for. The safe wrapper
//! here cannot check that, so it states it instead.
//!
//! ## What this module deliberately does not do
//!
//! No frames, no callbacks, no channel hopping, no MAC. It is the floor: bring the radio up in
//! 802.15.4 mode. Transmitting one frame is the next step, and receiving one -- which needs the
//! interrupt plumbing this project has got wrong twice -- is the step after that.

use crate::{RAIL_Handle_t, RAIL_IEEE802154_Config_t, RAIL_Status_t};

/// Configures the radio for 802.15.4 at 2.4 GHz.
///
/// Call after `RAIL_Init`. Returns the vendor status word unchanged: this wrapper does not interpret
/// it, because interpreting a status the caller cannot act on differently is a way of losing it.
/// # Safety
///
/// `handle` must come from a successful `RAIL_Init` and must not be used concurrently by another
/// caller. RAIL keeps mutable state behind this pointer; two threads in it at once is undefined
/// behaviour, and the C side does not protect itself.
pub unsafe fn config_2p4ghz(handle: RAIL_Handle_t) -> RAIL_Status_t {
    // SAFETY: `handle` comes from RAIL_Init and is live for as long as the caller keeps it, which is
    // RAIL's own contract; the function writes only radio state.
    unsafe { crate::RAIL_IEEE802154_Config2p4GHzRadio(handle) }
}

/// Applies an 802.15.4 configuration to the radio.
///
/// The configuration is the vendor's struct, generated by bindgen from `rail_ieee802154.h` -- not
/// mirrored by hand. A hand-written mirror of a seven-field C struct with nested unions is precisely
/// the kind of defect that compiles and then corrupts memory, and this crate has bindgen for that
/// reason.
/// # Safety
///
/// As [`config_2p4ghz`]: the handle must be a live RAIL handle, used by one caller at a time.
/// `config` must stay alive and unchanged for the duration of the call.
pub unsafe fn init(handle: RAIL_Handle_t, config: &RAIL_IEEE802154_Config_t) -> RAIL_Status_t {
    // SAFETY: the struct is `#[repr(C)]` from the same header the blob was built from, and `init`
    // copies what it needs; the pointer does not escape the call.
    unsafe { crate::RAIL_IEEE802154_Init(handle, config) }
}
