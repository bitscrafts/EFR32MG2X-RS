//! `BURTC` against `SYSRTC` over a known window: two counters on the same 32.768 kHz branch, and a control that takes the
//! branch away.
//!
//! ## What is being proved, and why it needs four runs
//!
//! `BURTC` is the counter a product reads after hibernating, so the only thing that matters about it is the rate it
//! counts at. A counter that counts at half the rate still counts, still reads back plausible numbers and still looks
//! alive on a debugger; the defect only shows up days later. The record therefore compares `BURTC` against `SYSRTC` --
//! both driven by LFRCO, so their deltas over the same window must agree -- and does it at two prescalers, because the
//! prescaler is the one place where a factor of two hides:
//!
//! 1. **Prescaler 0 (divide by 1).** Over a one-second window `BURTC` must advance within 1 % of what `SYSRTC` advanced.
//!    A block counting at the wrong rate, or not at all, fails here.
//! 2. **Prescaler 3 (divide by 8).** The same window must show one eighth of the count -- 125 per mille to within the
//!    same band. A prescaler that is written and silently ignored passes run 1 and fails here.
//! 3. **Control: source removed.** With `EM4GRPACLK` pointed at nothing and nothing else touched, the counter must stop
//!    dead while `SYSRTC` keeps counting. Without this run, "the counter advanced" would not distinguish a clocked
//!    counter from a register that reads whatever it last held.
//! 4. **Source restored.** The same call puts the source back, and the counter must count again. This is the run that
//!    makes the control bidirectional: run 3 alone would also be satisfied by a block that stopped for ever.
//!
//! ## What would make this instrument lie
//!
//! Two counters on one oscillator agreeing is a weak statement about absolute accuracy -- it says the block counts at
//! the branch's rate, not that the branch is 32768 Hz. That is the claim being made, and the record says so: no number
//! here is a frequency in hertz of anything but the ratio. The window is generated by the board's own `SysTick` delay,
//! and its length does not enter any ratio: both counters cover the same wall time whatever that length is.
//!
//! VERIFIED ON HARDWARE (2026-11-27): see `docs/04-reference/BURTC-2026-11-27.md` for the record and for what each run
//! ruled out.

#![no_std]
#![no_main]

use efr32mg2x_hal::board::Board;
use efr32mg2x_hal::burtc;
use efr32mg2x_hal::entry;
use efr32mg2x_hal::record::Record;
use embedded_hal::delay::DelayNs;
use panic_probe as _;

#[path = "common/mailbox.rs"]
mod mailbox;

use defmt_rtt as _;

/// The window both counters are measured over.
const WINDOW_MS: u32 = 1_000;

/// The shorter window used to show the counter resumes when the source comes back.
const BACK_WINDOW_MS: u32 = 500;

/// `CNTPRESC = 3` is divide by 8, so a full-rate window should show an eighth of the ticks.
const DIV8: u8 = 3;

/// Ticks per thousand of `SYSRTC` the full-rate window must show: 990..=1010 is the 1 % band the queue asks for.
const RATIO_MIN: u32 = 990;
const RATIO_MAX: u32 = 1_010;

/// Ticks per thousand at divide by 8: 125 nominal, with the same 1 % band around it.
const RATIO_DIV8_MIN: u32 = 120;
const RATIO_DIV8_MAX: u32 = 130;

/// Progress, written at every step: "no record" then says something died and where.
///
///   1 the peripherals were taken | 2 SYSRTC taken | 3 BURTC taken | 4 run 1 done | 5 run 2 done | 6 control done
///   7 restored | 8 record built
#[used]
#[no_mangle]
static ETAPAS: [core::sync::atomic::AtomicU32; 9] =
    [const { core::sync::atomic::AtomicU32::new(0) }; 9];

fn etapa(i: usize, v: u32) {
    ETAPAS[i].store(v, core::sync::atomic::Ordering::Relaxed);
}

/// Ticks of `burtc` per thousand ticks of `sysrtc`; zero when the reference did not move, which no band accepts.
fn per_mille(burtc_ticks: u32, sysrtc_ticks: u32) -> u32 {
    if sysrtc_ticks == 0 {
        return 0;
    }
    (u64::from(burtc_ticks) * 1_000 / u64::from(sysrtc_ticks)) as u32
}

/// One window: `(burtc ticks, sysrtc ticks)` over `ms` milliseconds, both read as close together as the two reads allow.
fn window(
    burtc: &burtc::Burtc,
    rtc: &efr32mg2x_hal::sysrtc::Sysrtc,
    delay: &mut impl DelayNs,
    ms: u32,
) -> (u32, u32) {
    let b0 = burtc.counter();
    let s0 = rtc.now();
    delay.delay_ms(ms);
    let s1 = rtc.now();
    let b1 = burtc.counter();
    (b1.wrapping_sub(b0), s1.wrapping_sub(s0))
}

#[entry]
fn main() -> ! {
    mailbox::invalidate();

    let board = match Board::take() {
        Some(board) => {
            etapa(0, 1);
            board
        }
        None => {
            etapa(0, 9);
            mailbox::fail(b"burtc: peripherals taken twice");
            loop {
                cortex_m::asm::wfi();
            }
        }
    };

    let rtc = match board.sysrtc() {
        Ok(rtc) => {
            etapa(1, 1);
            rtc
        }
        Err(_) => {
            etapa(1, 9);
            mailbox::fail(b"burtc: SYSRTC already handed out, so nothing to compare against");
            loop {
                cortex_m::asm::wfi();
            }
        }
    };

    let mut counter = match board.burtc(0) {
        Ok(counter) => {
            etapa(2, 1);
            counter
        }
        Err(e) => {
            etapa(2, 9);
            let mut record: Record<100> = Record::new();
            record.s(b"burtc: refused ").u(match e {
                efr32mg2x_hal::board::Handout::Taken(_) => 1u32,
                efr32mg2x_hal::board::Handout::Driver(_) => 2u32,
            });
            mailbox::fail(record.bytes());
            loop {
                cortex_m::asm::wfi();
            }
        }
    };

    let mut delay = board.delay();

    // ---- run 1: prescaler 0, full rate --------------------------------------------------------------------------
    let (d0, s0) = window(&counter, &rtc, &mut delay, WINDOW_MS);
    let r0 = per_mille(d0, s0);
    etapa(3, 1);

    // ---- run 2: prescaler 3, divide by 8 ------------------------------------------------------------------------
    // The write is checked by the driver; `pd` is what the field reads back afterwards, so a prescaler that did not
    // take shows in the record as a number and not only as a failed ratio.
    let prescaler_set = counter.set_prescaler(DIV8).is_ok();
    let pd = counter.prescaler();
    let (d1, s1) = window(&counter, &rtc, &mut delay, WINDOW_MS);
    let r1 = per_mille(d1, s1);
    etapa(4, 1 + prescaler_set as u32);

    // ---- run 3: control, source removed -------------------------------------------------------------------------
    let _ = counter.set_prescaler(0);
    burtc::remove_source();
    let (ctl, cs) = window(&counter, &rtc, &mut delay, WINDOW_MS);
    etapa(5, 1);

    // ---- run 4: source restored ---------------------------------------------------------------------------------
    burtc::select_lfrco();
    let (bk, bs) = window(&counter, &rtc, &mut delay, BACK_WINDOW_MS);
    let rb = per_mille(bk, bs);
    etapa(6, 1);

    let running = counter.is_running();
    let prescaler = counter.prescaler();
    let flags = counter.flags();
    let syncbusy = counter.syncbusy();
    let status = counter.status();
    let clocks = burtc::clock_readback();
    etapa(7, 1);

    let ok = running
        && prescaler_set
        && prescaler == 0
        && (RATIO_MIN..=RATIO_MAX).contains(&r0)
        && pd == DIV8
        && (RATIO_DIV8_MIN..=RATIO_DIV8_MAX).contains(&r1)
        && ctl == 0
        && cs > 0
        && bk > 0
        && (RATIO_MIN..=RATIO_MAX).contains(&rb);

    let mut record: Record<200> = Record::new();
    record
        .s(b"burtc: ok=")
        .u(ok as u32)
        .s(b" run=")
        .u(running as u32)
        .s(b" pre=")
        .u(prescaler)
        .s(b" d0=")
        .u(d0)
        .s(b" s0=")
        .u(s0)
        .s(b" r0=")
        .u(r0)
        .s(b" pd=")
        .u(pd)
        .s(b" d1=")
        .u(d1)
        .s(b" s1=")
        .u(s1)
        .s(b" r1=")
        .u(r1)
        .s(b" ctl=")
        .u(ctl)
        .s(b" cs=")
        .u(cs)
        .s(b" bk=")
        .u(bk)
        .s(b" bs=")
        .u(bs)
        .s(b" rb=")
        .u(rb)
        .s(b" if=0x")
        .h32(flags)
        .s(b" st=0x")
        .h32(status)
        .s(b" sb=0x")
        .h32(syncbusy)
        .s(b" ck=0x")
        .h32(clocks);
    etapa(8, 1);

    if ok {
        mailbox::pass(record.bytes());
    } else {
        mailbox::fail(record.bytes());
    }

    loop {
        cortex_m::asm::wfi();
    }
}
