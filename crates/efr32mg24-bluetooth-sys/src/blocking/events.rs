//! BLE Event System
//!
//! Type-safe event handling for Bluetooth Low Energy stack events.
//!
//! # Architecture
//!
//! ```text
//! Application
//!     ↓
//! poll_event() → BleEvent enum
//!     ↓
//! sl_bt_pop_event() → sl_bt_msg_t (FFI)
//! ```
//!
//! # Event Flow
//!
//! 1. **Polling**: Call `poll_event()` in main loop
//! 2. **Parsing**: Raw BGAPI event converted to typed `BleEvent`
//! 3. **Automatic State**: Connection state updated automatically
//! 4. **User Handling**: Match on event variants for custom logic
//!
//! # Example
//!
//! ```no_run
//! use efr32mg24_bluetooth_sys::blocking::{Bluetooth, BleEvent};
//!
//! let mut ble = Bluetooth::new(&mut delay)?;
//! ble.set_device_name("My Device")?;
//! ble.start_connectable(100, 0)?;
//!
//! loop {
//!     // Poll for events
//!     if let Some(event) = ble.poll_event() {
//!         match event {
//!             BleEvent::Connected { connection, .. } => {
//!                 // Connection state updated automatically!
//!                 // Just handle custom logic here
//!             }
//!             BleEvent::Disconnected { reason } => {
//!                 // Automatically resume advertising
//!                 ble.start_connectable(100, 0)?;
//!             }
//!             BleEvent::GattWrite { attribute, value } => {
//!                 // Handle GATT writes
//!             }
//!             _ => {}
//!         }
//!     }
//!     delay.delay_ms(10);
//! }
//! ```

use crate::ffi as bt;

/// Bluetooth Low Energy event
///
/// Type-safe representation of BGAPI events. Events are generated by the
/// Bluetooth stack and polled via `Bluetooth::poll_event()`.
///
/// # Event Categories
///
/// - **Connection**: Device connected/disconnected
/// - **GATT**: Characteristic reads/writes from client
/// - **Advertising**: Advertising timeout, scan requests
///
/// # Automatic State Management
///
/// The following state is managed automatically by the event system:
/// - Connection status (`is_connected()`)
/// - Connection handle (for GATT operations)
/// - Advertising state (future)
#[derive(Debug, Clone)]
// The largest variant carries a 512-byte heapless buffer, because a GATT write can be that big and
// this crate has no allocator to box it. The alternative -- a smaller variant behind a pointer --
// would need an allocator or a static pool, and the pool would be the same 512 bytes.
#[allow(clippy::large_enum_variant)]
pub enum BleEvent {
    /// A security-manager event: pairing started, a bond was stored, or pairing failed.
    Security {
        /// 0 passkey display, 1 passkey request, 2 confirm passkey, 3 bonded, 4 bonding failed
        /// (`confirm bonding` has its own variant, `ConfirmBonding`, because its layout differs).
        event: u8,
        /// The connection handle.
        connection: u8,
        /// The security manager's error code, meaningful for `event == 4`.
        reason: u16,
    },

    /// The stack asks whether a pairing may create a bond (`sl_bt_evt_sm_confirm_bonding`).
    ///
    /// Its payload is `(connection: u8, bonding_handle: u8)` (`sl_bt_api.h`, `sl_bt_evt_sm_confirm_bonding_s`). It used
    /// to be decoded through the `bonding_failed` layout, which reads a `u16` reason out of what is a `u8` handle, so
    /// the field it reported was the handle byte plus whatever followed it in the buffer.
    ConfirmBonding {
        /// The connection handle.
        connection: u8,
        /// The handle the stack will store the bond under if the answer is 1; 0xFF when it has none to give.
        bonding_handle: u8,
    },

    /// The link's parameters or security level changed (`sl_bt_evt_connection_parameters`).
    ///
    /// `security_mode` is the only device-side proof that a link is encrypted: 0 none, 1 unauthenticated encryption
    /// (what Just Works gives), 2 authenticated, 3 authenticated Secure Connections. `Bonded: yes` on a host is the
    /// host's own storage and says nothing about this link.
    ConnectionParameters {
        /// The connection handle.
        connection: u8,
        /// Units of 1.25 ms.
        interval: u16,
        /// Slave latency: how many connection events the peripheral may skip.
        latency: u16,
        /// Units of 10 ms.
        timeout: u16,
        /// 0 none, 1 unauthenticated encryption, 2 authenticated, 3 authenticated Secure Connections.
        security_mode: u8,
        /// The maximum PDU payload the controller will send on this link, in bytes.
        txsize: u16,
    },

    /// The ATT MTU was negotiated (`sl_bt_evt_gatt_mtu_exchanged`). The default is 23 until this fires.
    Mtu {
        /// The connection handle.
        connection: u8,
        /// The negotiated MTU, in bytes.
        mtu: u16,
    },

    /// Remote device connected.
    ///
    /// # Automatic Actions
    /// - Connection state set to true
    /// - Connection handle saved
    /// - Advertising stopped (by stack)
    Connected {
        /// Connection handle (0-255).
        connection: u8,
        /// 6-byte Bluetooth address.
        address: [u8; 6],
        /// 0 = Public, 1 = Random.
        address_type: u8,
        /// True if the local device is the central.
        is_master: bool,
        /// Bonding handle (0xFF = no bonding).
        bonding: u8,
    },

    /// Remote device disconnected.
    ///
    /// # Common Reason Codes
    /// - `0x0213`: Connection timeout
    /// - `0x0216`: Connection terminated by remote device
    /// - `0x021E`: Connection terminated by local host
    ///
    /// # Automatic Actions
    /// - Connection state set to false
    /// - Connection handle cleared
    Disconnected {
        /// Connection handle that was closed.
        connection: u8,
        /// Disconnect reason code (BLE spec).
        reason: u16,
    },

    /// A remote client changed its subscription to one of this device's characteristics.
    ///
    /// This is the only observable trace a client leaves when it starts listening: a plain *read* is answered inside
    /// the stack from the attribute table and produces no event at all, which is why "the phone read the
    /// characteristic" cannot be proven from the device side -- only from the client side. A subscription can.
    Subscribed {
        /// Connection handle.
        connection: u8,
        /// GATT characteristic handle.
        characteristic: u16,
        /// Which part of the client configuration changed (`sl_bt_gatt_server_client_config` / `..._client_config`).
        status_flags: u8,
        /// The value the client wrote: 0 none, 1 notification, 2 indication.
        client_config: u16,
        /// Whether the client turned notifications (or indications) on.
        notifications: bool,
    },

    /// GATT characteristic written by remote client.
    ///
    /// # Example
    /// ```no_run
    /// match event {
    ///     BleEvent::GattWrite { attribute, value, .. } => {
    ///         if attribute == GATTDB_LED_CONTROL.value() {
    ///             let led_state = value[0];
    ///             // Update LED based on value
    ///         }
    ///     }
    ///     _ => {}
    /// }
    /// ```
    GattWrite {
        /// Connection handle.
        connection: u8,
        /// GATT characteristic handle.
        attribute: u16,
        /// Write offset (usually 0).
        offset: u16,
        /// Written data (max 512 bytes).
        value: heapless::Vec<u8, 512>,
    },

    /// GATT characteristic read by remote client (user read request).
    ///
    /// # Response Required
    /// Must respond with `gatt_server_send_user_read_response()` (future API)
    GattRead {
        /// Connection handle.
        connection: u8,
        /// GATT characteristic handle.
        attribute: u16,
        /// Read offset (usually 0).
        offset: u16,
    },

    /// GATT notification/indication transmission completed.
    ///
    /// Triggered after `notify()` succeeds. Can be used for flow control
    /// when sending multiple notifications.
    GattNotificationComplete {
        /// Connection handle.
        connection: u8,
    },

    /// Advertising timeout.
    ///
    /// Triggered when:
    /// - Max advertising events reached (set via `set_timing`)
    /// - Advertising duration expired
    AdvertisingTimeout {
        /// Advertising set handle.
        advertising_set: u8,
    },

    /// An advertisement was received while scanning (central role).
    ///
    /// The payload is the *raw* AD structure list — the same bytes a phone parses — so an
    /// application that wants the name has to walk it: `[len][type][value...]` repeated. It is kept
    /// raw on purpose: decoding belongs to whoever knows what they are looking for, and a
    /// half-decoder here would lose manufacturer data and service UUIDs.
    Advertisement {
        /// 6-byte advertiser address, in the controller's reverse byte order.
        address: [u8; 6],
        /// 0 = public, 1 = random.
        address_type: u8,
        /// Received signal strength in dBm (a negative number; -40 is close, -90 is far).
        rssi: i8,
        /// The raw advertising payload, at most 31 bytes for legacy PDUs.
        data: heapless::Vec<u8, 31>,
    },

    /// An event this crate does not decode yet, carrying the stack's own event ID.
    ///
    /// Returned rather than dropped so a new vendor event cannot panic the application between two
    /// stack releases.
    Unknown {
        /// The BGAPI event ID, as `sl_bt_pop_event` reported it.
        event_id: u32,
    },
}

impl BleEvent {
    /// Parse raw BGAPI event into typed BleEvent
    ///
    /// # Safety
    ///
    /// Caller must ensure `evt` contains a valid event populated by `sl_bt_pop_event()`.
    ///
    /// # Arguments
    ///
    /// - `evt`: Pointer to `sl_bt_msg_t` structure from BGAPI
    ///
    /// # Returns
    ///
    /// Parsed `BleEvent` or `None` if event is empty (status != 0)
    pub(super) unsafe fn parse(evt: &bt::sl_bt_msg_t) -> Option<Self> {
        // **The id is the header masked, not the header.** `SL_BGAPI_MSG_ID(HDR)` is `HDR & 0xffff00f8` in
        // `sl_bgapi.h`, because the low three bits are flags that vary per message. Matching the raw header works
        // only while those bits happen to be zero, and the failure is silent: every event the stack delivers falls
        // through the match and `poll_event` returns `None`, which is indistinguishable from an empty queue.
        //
        // Measured on this board: a two-second scan delivered 41 events with id `0x010500a0` and the parser
        // recognised none of them, while the radio was demonstrably receiving (`RAIL_ScheduleRx` 601 calls, every one
        // status 0).
        let event_id = evt.header & 0xffff_00f8;

        // Match on event ID constants
        match event_id {
            // Connection opened (peripheral role)
            bt::sl_bt_evt_connection_opened_id => {
                let data = unsafe { evt.data.evt_connection_opened.as_ref() };
                Some(BleEvent::Connected {
                    connection: data.connection,
                    address: data.address.addr,
                    address_type: data.address_type,
                    is_master: data.master != 0,
                    bonding: data.bonding,
                })
            }

            // The security manager. These were unmapped until a pairing attempt failed with nothing to read: the
            // event reached this parser and its payload was dropped, which is why the abort looked like silence.
            bt::sl_bt_evt_sm_passkey_display_id
            | bt::sl_bt_evt_sm_passkey_request_id
            | bt::sl_bt_evt_sm_confirm_passkey_id
            | bt::sl_bt_evt_sm_bonded_id
            | bt::sl_bt_evt_sm_bonding_failed_id => {
                let data = unsafe { evt.data.evt_sm_bonding_failed.as_ref() };
                let event = match event_id {
                    bt::sl_bt_evt_sm_passkey_display_id => 0u8,
                    bt::sl_bt_evt_sm_passkey_request_id => 1,
                    bt::sl_bt_evt_sm_confirm_passkey_id => 2,
                    bt::sl_bt_evt_sm_bonded_id => 3,
                    _ => 4,
                };
                // Both `bonded` and `bonding_failed` carry (connection, reason) in that order; the reason field is
                // only meaningful on failure, and reading it on success costs nothing.
                Some(BleEvent::Security {
                    event,
                    connection: data.connection,
                    reason: data.reason,
                })
            }

            bt::sl_bt_evt_sm_confirm_bonding_id => {
                let data = unsafe { evt.data.evt_sm_confirm_bonding.as_ref() };
                Some(BleEvent::ConfirmBonding {
                    connection: data.connection,
                    bonding_handle: data.bonding_handle,
                })
            }

            bt::sl_bt_evt_connection_parameters_id => {
                let data = unsafe { evt.data.evt_connection_parameters.as_ref() };
                Some(BleEvent::ConnectionParameters {
                    connection: data.connection,
                    interval: data.interval,
                    latency: data.latency,
                    timeout: data.timeout,
                    security_mode: data.security_mode,
                    txsize: data.txsize,
                })
            }

            bt::sl_bt_evt_gatt_mtu_exchanged_id => {
                let data = unsafe { evt.data.evt_gatt_mtu_exchanged.as_ref() };
                Some(BleEvent::Mtu {
                    connection: data.connection,
                    mtu: data.mtu,
                })
            }

            // Connection closed
            bt::sl_bt_evt_connection_closed_id => {
                let data = unsafe { evt.data.evt_connection_closed.as_ref() };
                Some(BleEvent::Disconnected {
                    connection: data.connection,
                    reason: data.reason,
                })
            }

            // **The compat scanner's report.** With the `scanner` component enabled and neither `legacy_scanner` nor
            // `extended_scanner` present, the stack reports through this event (`0x010500a0`), not through
            // `sl_bt_evt_scanner_legacy_advertisement_report` (`0x000500a0`). Measured on the board: two seconds of
            // scanning handed over 39 events and the parser recognised none of them, because only the legacy id was
            // mapped -- the radio was receiving the whole time (`RAIL_ScheduleRx` 601 calls, all status 0).
            //
            // Same payload contract as the legacy report for the fields this API exposes: address (6 bytes, in the
            // controller's order), address type, RSSI as i8, and a length-prefixed flexible array.
            bt::sl_bt_evt_scanner_scan_report_id => {
                let data = unsafe { evt.data.evt_scanner_scan_report.as_ref() };
                let len = (data.data.len as usize).min(31);
                let mut payload: heapless::Vec<u8, 31> = heapless::Vec::new();
                for i in 0..len {
                    let byte = unsafe { data.data.data.as_ptr().add(i).read() };
                    let _ = payload.push(byte);
                }
                Some(BleEvent::Advertisement {
                    address: data.address.addr,
                    address_type: data.address_type,
                    rssi: data.rssi,
                    data: payload,
                })
            }

            // A client turned notifications on or off. `status_flags` reports which part of the client configuration
            // changed; `client_config_flags` carries the value, and `sl_bt_gatt_server_notification` (1) is the bit
            // that means "notify me".
            bt::sl_bt_evt_gatt_server_characteristic_status_id => {
                let data = unsafe { evt.data.evt_gatt_server_characteristic_status.as_ref() };
                Some(BleEvent::Subscribed {
                    connection: data.connection,
                    characteristic: data.characteristic,
                    status_flags: data.status_flags,
                    client_config: data.client_config_flags,
                    notifications: (data.client_config_flags & 0x0001) != 0,
                })
            }

            // A legacy advertisement seen by the scanner (central role)
            bt::sl_bt_evt_scanner_legacy_advertisement_report_id => {
                let data = unsafe { evt.data.evt_scanner_legacy_advertisement_report.as_ref() };
                let len = (data.data.len as usize).min(31);
                let mut payload: heapless::Vec<u8, 31> = heapless::Vec::new();
                for i in 0..len {
                    // Flexible array member: read through the pointer, see the note on GATT values.
                    let byte = unsafe { data.data.data.as_ptr().add(i).read() };
                    let _ = payload.push(byte);
                }
                Some(BleEvent::Advertisement {
                    address: data.address.addr,
                    address_type: data.address_type,
                    rssi: data.rssi,
                    data: payload,
                })
            }

            // GATT server attribute value (write from client)
            bt::sl_bt_evt_gatt_server_attribute_value_id => {
                let data = unsafe { evt.data.evt_gatt_server_attribute_value.as_ref() };

                // Copy value data to heapless::Vec
                let len = data.value.len as usize;
                let mut value: heapless::Vec<u8, 512> = heapless::Vec::new();
                for i in 0..len.min(512) {
                    // Truncate to 512 bytes max. `data.value.data` is a flexible array member —
                    // bindgen's `__IncompleteArrayField` has no length and no `Index`, so the byte
                    // is read through its pointer. The length came from the header's own `len`.
                    let byte = unsafe { data.value.data.as_ptr().add(i).read() };
                    let _ = value.push(byte);
                }

                Some(BleEvent::GattWrite {
                    connection: data.connection,
                    attribute: data.attribute,
                    offset: data.offset,
                    value,
                })
            }

            // GATT server user read request
            bt::sl_bt_evt_gatt_server_user_read_request_id => {
                let data = unsafe { evt.data.evt_gatt_server_user_read_request.as_ref() };
                Some(BleEvent::GattRead {
                    connection: data.connection,
                    // The header names this field `characteristic`; it is the same 16-bit handle
                    // the write path calls `attribute`. Two names for one thing across two
                    // events, which is a good reason to keep the conversion in one place.
                    attribute: data.characteristic,
                    offset: data.offset,
                })
            }

            // GATT notification transmission completed
            bt::sl_bt_evt_gatt_server_notification_tx_completed_id => {
                let data = unsafe { evt.data.evt_gatt_server_notification_tx_completed.as_ref() };
                Some(BleEvent::GattNotificationComplete {
                    connection: data.connection,
                })
            }

            // Advertising timeout
            bt::sl_bt_evt_advertiser_timeout_id => {
                let data = unsafe { evt.data.evt_advertiser_timeout.as_ref() };
                Some(BleEvent::AdvertisingTimeout {
                    advertising_set: data.handle,
                })
            }

            // Unknown/unimplemented event
            _ => Some(BleEvent::Unknown { event_id }),
        }
    }
}
