//! BLE Event System
//!
//! Type-safe event handling for Bluetooth Low Energy stack events.
//!
//! # Architecture
//!
//! ```text
//! Application
//!     ↓
//! poll_event() → BleEvent enum
//!     ↓
//! sl_bt_pop_event() → sl_bt_msg_t (FFI)
//! ```
//!
//! # Event Flow
//!
//! 1. **Polling**: Call `poll_event()` in main loop
//! 2. **Parsing**: Raw BGAPI event converted to typed `BleEvent`
//! 3. **Automatic State**: Connection state updated automatically
//! 4. **User Handling**: Match on event variants for custom logic
//!
//! # Example
//!
//! ```no_run
//! use xiao_mg24_bsp::Board;
//! use xiao_mg24_bsp::radio::ble::{XiaoBle, BleEvent};
//!
//! let board = Board::take().unwrap();
//! let mut delay = board.into_delay();
//! let mut ble = XiaoBle::init(&mut delay)?;
//!
//! ble.set_device_name("XIAO Device")?;
//! ble.start_connectable(100, 0)?;
//!
//! loop {
//!     // Poll for events
//!     if let Some(event) = ble.poll_event() {
//!         match event {
//!             BleEvent::Connected { connection, .. } => {
//!                 // Connection state updated automatically!
//!                 // Just handle custom logic here
//!             }
//!             BleEvent::Disconnected { reason } => {
//!                 // Automatically resume advertising
//!                 ble.start_connectable(100, 0)?;
//!             }
//!             BleEvent::GattWrite { attribute, value } => {
//!                 // Handle GATT writes
//!             }
//!             _ => {}
//!         }
//!     }
//!     delay.delay_ms(10);
//! }
//! ```

use super::BleError;
use efr32mg24_bluetooth_sys as bt;

/// Bluetooth Low Energy event
///
/// Type-safe representation of BGAPI events. Events are generated by the
/// Bluetooth stack and polled via `XiaoBle::poll_event()`.
///
/// # Event Categories
///
/// - **Connection**: Device connected/disconnected
/// - **GATT**: Characteristic reads/writes from client
/// - **Advertising**: Advertising timeout, scan requests
///
/// # Automatic State Management
///
/// The following state is managed automatically by the event system:
/// - Connection status (`is_connected()`)
/// - Connection handle (for GATT operations)
/// - Advertising state (future)
#[derive(Debug, Clone)]
pub enum BleEvent {
    /// Remote device connected
    ///
    /// # Fields
    /// - `connection`: Connection handle (0-255)
    /// - `address`: 6-byte Bluetooth address [u8; 6]
    /// - `address_type`: 0 = Public, 1 = Random
    /// - `is_master`: True if local device is central role
    /// - `bonding`: Bonding handle (0xFF = no bonding)
    ///
    /// # Automatic Actions
    /// - Connection state set to true
    /// - Connection handle saved
    /// - Advertising stopped (by stack)
    Connected {
        connection: u8,
        address: [u8; 6],
        address_type: u8,
        is_master: bool,
        bonding: u8,
    },

    /// Remote device disconnected
    ///
    /// # Fields
    /// - `connection`: Connection handle that was closed
    /// - `reason`: Disconnect reason code (BLE spec)
    ///
    /// # Common Reason Codes
    /// - `0x0213`: Connection timeout
    /// - `0x0216`: Connection terminated by remote device
    /// - `0x021E`: Connection terminated by local host
    ///
    /// # Automatic Actions
    /// - Connection state set to false
    /// - Connection handle cleared
    Disconnected { connection: u8, reason: u16 },

    /// GATT characteristic written by remote client
    ///
    /// # Fields
    /// - `connection`: Connection handle
    /// - `attribute`: GATT characteristic handle
    /// - `offset`: Write offset (usually 0)
    /// - `value`: Written data (max 512 bytes)
    ///
    /// # Example
    /// ```no_run
    /// match event {
    ///     BleEvent::GattWrite { attribute, value, .. } => {
    ///         if attribute == GATTDB_LED_CONTROL.value() {
    ///             let led_state = value[0];
    ///             // Update LED based on value
    ///         }
    ///     }
    ///     _ => {}
    /// }
    /// ```
    GattWrite {
        connection: u8,
        attribute: u16,
        offset: u16,
        value: heapless::Vec<u8, 512>,
    },

    /// GATT characteristic read by remote client (user read request)
    ///
    /// # Fields
    /// - `connection`: Connection handle
    /// - `attribute`: GATT characteristic handle
    /// - `offset`: Read offset (usually 0)
    ///
    /// # Response Required
    /// Must respond with `gatt_server_send_user_read_response()` (future API)
    GattRead {
        connection: u8,
        attribute: u16,
        offset: u16,
    },

    /// GATT notification/indication transmission completed
    ///
    /// # Fields
    /// - `connection`: Connection handle
    ///
    /// Triggered after `notify()` succeeds. Can be used for flow control
    /// when sending multiple notifications.
    GattNotificationComplete { connection: u8 },

    /// Advertising timeout
    ///
    /// # Fields
    /// - `advertising_set`: Advertising set handle
    ///
    /// Triggered when:
    /// - Max advertising events reached (set via `set_timing`)
    /// - Advertising duration expired
    AdvertisingTimeout { advertising_set: u8 },

    /// Unknown event
    ///
    /// Events not yet implemented are returned as Unknown with the event ID.
    /// This prevents panics when new events are added by Silicon Labs.
    Unknown { event_id: u32 },
}

impl BleEvent {
    /// Parse raw BGAPI event into typed BleEvent
    ///
    /// # Safety
    ///
    /// Caller must ensure `evt` contains a valid event populated by `sl_bt_pop_event()`.
    ///
    /// # Arguments
    ///
    /// - `evt`: Pointer to `sl_bt_msg_t` structure from BGAPI
    ///
    /// # Returns
    ///
    /// Parsed `BleEvent` or `None` if event is empty (status != 0)
    pub(super) unsafe fn parse(evt: &bt::sl_bt_msg_t) -> Option<Self> {
        // Extract event ID from header
        // Header format: [31:24] = class, [23:16] = command, [15:0] = unused
        // Event ID is the full header value
        let event_id = evt.header;

        // Match on event ID constants
        match event_id {
            // Connection opened (peripheral role)
            bt::sl_bt_evt_connection_opened_id => {
                let data = &evt.data.evt_connection_opened;
                Some(BleEvent::Connected {
                    connection: data.connection,
                    address: data.address.addr,
                    address_type: data.address_type,
                    is_master: data.master != 0,
                    bonding: data.bonding,
                })
            }

            // Connection closed
            bt::sl_bt_evt_connection_closed_id => {
                let data = &evt.data.evt_connection_closed;
                Some(BleEvent::Disconnected {
                    connection: data.connection,
                    reason: data.reason,
                })
            }

            // GATT server attribute value (write from client)
            bt::sl_bt_evt_gatt_server_attribute_value_id => {
                let data = &evt.data.evt_gatt_server_attribute_value;

                // Copy value data to heapless::Vec
                let len = data.value.len as usize;
                let mut value: heapless::Vec<u8, 512> = heapless::Vec::new();
                for i in 0..len.min(512) {
                    // Truncate to 512 bytes max
                    let _ = value.push(data.value.data[i]);
                }

                Some(BleEvent::GattWrite {
                    connection: data.connection,
                    attribute: data.attribute,
                    offset: data.offset,
                    value,
                })
            }

            // GATT server user read request
            bt::sl_bt_evt_gatt_server_user_read_request_id => {
                let data = &evt.data.evt_gatt_server_user_read_request;
                Some(BleEvent::GattRead {
                    connection: data.connection,
                    attribute: data.attribute,
                    offset: data.offset,
                })
            }

            // GATT notification transmission completed
            bt::sl_bt_evt_gatt_server_notification_tx_completed_id => {
                let data = &evt.data.evt_gatt_server_notification_tx_completed;
                Some(BleEvent::GattNotificationComplete {
                    connection: data.connection,
                })
            }

            // Advertising timeout
            bt::sl_bt_evt_advertiser_timeout_id => {
                let data = &evt.data.evt_advertiser_timeout;
                Some(BleEvent::AdvertisingTimeout {
                    advertising_set: data.handle,
                })
            }

            // Unknown/unimplemented event
            _ => Some(BleEvent::Unknown { event_id }),
        }
    }
}
