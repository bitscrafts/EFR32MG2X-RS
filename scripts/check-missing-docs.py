#!/usr/bin/env python3
"""Every crate that ships denies `missing_docs` -- and the lint is proven live, not merely spelled.

Why this exists: `#![deny(missing_docs)]` is not a number, it is a mechanism. A crate that carries it
cannot gain an undocumented public item without failing to compile, in every build, on every machine
-- which is more than any list of documented items can promise. The measurement on 2026-11-27 was 0
undocumented items across 33 crates (with `--measure`), and the six crates that carried 74 hand-written
undocumented items before the attribute was installed are named in
`docs/04-reference/MISSING-DOCS-2026-11-27.md`.

What this script checks, and what each check would miss on its own:

  attribute   every workspace crate's lib root carries the lint. A crate cannot silently opt out.
  allows      the only `allow(missing_docs)` in the tree is on a module that includes generated
              code, and there is exactly one per generated module. Without this check the attribute
              above is worth nothing: one `#[allow]` in a module would suppress the lint there and
              the gate would still see the deny at the root.
  control     a fixture crate with an undocumented public item, carrying the same attribute, must
              FAIL to compile; the same item with a doc must compile. This is the difference
              between checking that a rule is written down and checking that it fires -- the failure
              mode this repository has hit before is a check that passes while the live path is
              broken.
  floor       fewer crates inspected than the floor is a failure, not a pass: a broken `cargo
              metadata` would otherwise report "0 crates, 0 problems".

`--measure` additionally compiles every crate with `-D missing_docs` and counts the diagnostics; it is
the number, and it is what the record quotes. It is not the default because it rebuilds each crate with
different rustc arguments, which throws away the gate's cache for the steps that follow.

Usage:
    python3 scripts/check-missing-docs.py            # gate mode: mechanism + control
    python3 scripts/check-missing-docs.py --measure  # also count, crate by crate
    python3 scripts/check-missing-docs.py --check    # accepted for symmetry with the other checkers
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# A crate that stops being inspected must be noticed. The workspace has 33 lib targets; the floor is
# below that so a crate being deleted is not a failure, but a metadata call returning nothing is.
MIN_CRATES = 30

# The only modules allowed to carry `#[allow(missing_docs)]`: the two places where bindgen output is
# included. Each entry is (crate directory, module, why it is generated). The check below verifies that
# the module really does include generated code, so this table cannot be used to silence hand-written
# code -- that is what the table is for, and a table nobody verifies is a hole.
GENERATED_MODULES = [
    (
        "crates/efr32mg24-rail-sys",
        "ffi",
        "rail.h: bindgen output, 254 items, regenerated by build.rs on every build",
    ),
    (
        "crates/efr32mg24-bluetooth-sys",
        "ffi",
        "sl_bt_api.h: bindgen output, 600 items, regenerated by build.rs on every build",
    ),
]

DENY_RE = re.compile(r"^\s*#!\[\s*deny\(([^)]*)\)\s*\]", re.MULTILINE)
ALLOW_RE = re.compile(r"^\s*#!?\[\s*allow\(\s*missing_docs\s*\)\s*\]", re.MULTILINE)


def run(cmd: list[str], cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        cmd, cwd=str(cwd or REPO), capture_output=True, text=True, timeout=1800
    )


def workspace_packages() -> list[dict]:
    out = run(["cargo", "metadata", "--no-deps", "--format-version", "1"])
    if out.returncode != 0:
        print(f"  FAIL  cargo metadata: {out.stderr.strip().splitlines()[:1]}")
        sys.exit(1)
    return json.loads(out.stdout)["packages"]


def lib_target(pkg: dict) -> dict | None:
    for t in pkg["targets"]:
        if "lib" in t["kind"]:
            return t
    return None


def has_crate_deny(root: Path) -> bool:
    """The deny has to be a crate attribute, before any item, and unconditional.

    `#![cfg_attr(feature = "x", deny(missing_docs))]` is not accepted: a lint that is on for one
    feature is off for the build most people use.
    """
    text = root.read_text()
    head = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):
            continue
        if stripped.startswith("#!["):
            head.append(stripped)
            continue
        break
    for attr in head:
        if attr.startswith("#![cfg_attr"):
            continue
        m = DENY_RE.match(attr)
        if m and "missing_docs" in m.group(1):
            return True
    return False


def allows_in(pkg_dir: Path) -> list[tuple[Path, int, str]]:
    found = []
    for path in sorted(pkg_dir.rglob("*.rs")):
        # `target/` inside a crate directory would contain copies of the same source; there is none
        # today, and skipping it keeps the check honest if one appears.
        if "target" in path.parts:
            continue
        for i, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
            if ALLOW_RE.match(line):
                found.append((path, i, line.strip()))
    return found


def lib_src(pkg: dict) -> Path:
    t = lib_target(pkg)
    assert t is not None, f"{pkg['name']} has no lib target"
    return Path(t["src_path"])


def allow_is_on_generated_module(path: Path, line_no: int) -> bool:
    """A permitted allow sits directly on a `pub mod` whose body includes `include!`."""
    lines = path.read_text(errors="replace").splitlines()
    # Wide enough for the module's own doc comment between the attribute and the include.
    rest = lines[line_no - 1 : line_no + 25]
    body = "\n".join(rest)
    return "pub mod" in body and "include!(" in body


def control(tmp: Path) -> tuple[bool, str]:
    """The lint must fire on an undocumented item and stay quiet on a documented one.

    Compiled with plain rustc: the question is whether the lint is alive, and a cargo project would
    only add a manifest and a lockfile to the same answer.
    """
    undoc = tmp / "undoc.rs"
    undoc.write_text(
        "//! Fixture.\n"
        "#![deny(missing_docs)]\n"
        "pub fn no_doc_here() {}\n"
    )
    doc = tmp / "doc.rs"
    doc.write_text(
        "//! Fixture.\n"
        "#![deny(missing_docs)]\n"
        "/// Documented, so this must compile.\n"
        "pub fn documented() {}\n"
    )
    bad = subprocess.run(
        ["rustc", "--crate-type", "lib", "--edition", "2021", "-o", str(tmp / "a.rlib"), str(undoc)],
        capture_output=True,
        text=True,
    )
    good = subprocess.run(
        ["rustc", "--crate-type", "lib", "--edition", "2021", "-o", str(tmp / "b.rlib"), str(doc)],
        capture_output=True,
        text=True,
    )
    fires = bad.returncode != 0 and "missing documentation" in bad.stderr
    quiet = good.returncode == 0
    detail = (
        f"undocumented item refused ({'yes' if fires else 'NO'}), "
        f"documented item accepted ({'yes' if quiet else 'NO'})"
    )
    return fires and quiet, detail


def measure(pkgs: list[dict]) -> tuple[int, list[str]]:
    total = 0
    failures = []
    for pkg in pkgs:
        out = run(["cargo", "rustc", "-p", pkg["name"], "--lib", "--", "-D", "missing_docs"])
        n = out.stderr.count("missing documentation")
        total += n
        if n or "error" in out.stderr:
            first = next(
                (l for l in out.stderr.splitlines() if "missing documentation" in l or l.startswith("error")),
                "unknown",
            )
            failures.append(f"{pkg['name']}: {n} undocumented ({first.strip()})")
    return total, failures


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="accepted for symmetry; this is the default")
    ap.add_argument("--measure", action="store_true", help="compile each crate with -D missing_docs")
    ap.add_argument(
        "--floor",
        type=int,
        default=MIN_CRATES,
        help=f"minimum number of crates to inspect (default {MIN_CRATES}); raising it is how the floor is tested",
    )
    args = ap.parse_args()

    pkgs = [p for p in workspace_packages() if lib_target(p)]
    failed = 0

    if len(pkgs) < args.floor:
        print(f"  FAIL  missing_docs: only {len(pkgs)} crates inspected, floor is {args.floor}")
        return 1

    # 1. The attribute, crate by crate.
    missing = []
    for pkg in pkgs:
        root = lib_src(pkg)
        if not has_crate_deny(root):
            missing.append(str(root.relative_to(REPO)))
    if missing:
        print(f"  FAIL  missing_docs: {len(missing)} crate(s) do not deny the lint")
        for m in missing:
            print(f"          {m}")
        failed = 1
    else:
        print(f"  PASS  missing_docs: {len(pkgs)} crates deny the lint at the crate root")

    # 2. The allows: only on generated modules, and only where generation is real.
    permitted = {(REPO / d / "src" / "lib.rs").resolve(): (mod, why) for d, mod, why in GENERATED_MODULES}
    seen = []
    for pkg in pkgs:
        pkg_dir = lib_src(pkg).parent.parent
        for path, line_no, text in allows_in(pkg_dir):
            key = path.resolve()
            entry = permitted.get(key)
            if entry is None:
                print(f"  FAIL  missing_docs: {path.relative_to(REPO)}:{line_no} allows the lint ({text})")
                print("          only a module that includes generated code may do that; see GENERATED_MODULES")
                failed = 1
                continue
            if text.startswith("#!["):
                print(f"  FAIL  missing_docs: {path.relative_to(REPO)}:{line_no} is crate-level, not module-level")
                failed = 1
                continue
            if not allow_is_on_generated_module(path, line_no):
                print(f"  FAIL  missing_docs: {path.relative_to(REPO)}:{line_no} does not sit on an include! module")
                failed = 1
                continue
            seen.append((key, entry[0]))
    for key, (mod, why) in permitted.items():
        if (key, mod) not in seen:
            print(f"  FAIL  missing_docs: the generated module `{mod}` in {key.relative_to(REPO)} lost its allow")
            print(f"          ({why}) -- either it stopped being generated or the exemption moved")
            failed = 1
    if not failed:
        print(f"  PASS  missing_docs: {len(seen)} generated module(s) exempt, both include! bindgen output")

    # 3. The control: the rule fires.
    with tempfile.TemporaryDirectory(prefix="missing-docs-") as tmp:
        ok, detail = control(Path(tmp))
    if ok:
        print(f"  PASS  missing_docs: control -- {detail}")
    else:
        print(f"  FAIL  missing_docs: control -- {detail}")
        failed = 1

    # 4. The number, on request.
    if args.measure:
        total, failures = measure(pkgs)
        if failures:
            print(f"  FAIL  missing_docs: {total} undocumented item(s) measured")
            for f in failures:
                print(f"          {f}")
            failed = 1
        else:
            print(f"  PASS  missing_docs: 0 undocumented items measured across {len(pkgs)} crates")

    if failed:
        print("  FAIL  missing_docs")
        return 1
    print(f"  PASS  missing_docs: {len(pkgs)} crates, mechanism installed and firing")
    return 0


if __name__ == "__main__":
    sys.exit(main())